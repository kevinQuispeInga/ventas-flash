/**
 * Obtiene las coordenadas base de un distrito de Lima y aplica una dispersión
 * realista (< 250m) para evitar que varios productos queden apilados.
 */
function getDistrictCoords(districtName: string, indexOffset = 0) {
  const found = LIMA_DISTRICTS.find((d) => d.district === districtName || d.name.includes(districtName)) || LIMA_DISTRICTS[0];
  const offsetLat = ((indexOffset % 7) - 3) * 0.0012;
  const offsetLon = (((indexOffset * 3) % 7) - 3) * 0.0012;
  return {
    latitude: Math.round((found.latitude + offsetLat) * 10000) / 10000,
    longitude: Math.round((found.longitude + offsetLon) * 10000) / 10000,
    locationLabel: `${found.district}, Lima`,
  };
}

